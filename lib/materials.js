export function marketLink(query, store = 'all') {
  const selected = STORES.find(item => item.id === store) || STORES[0];
  const url = new URL('https://www.google.com/search');
  url.searchParams.set('q', `${selected.domain ? `site:${selected.domain} ` : ''}${String(query).slice(0, 140)}`);
  return url.href;
}
